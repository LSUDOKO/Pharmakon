"""Lay VO lines onto scenes → film/src/timing.ts (single source of timing for every scene)."""
import json, math
from pathlib import Path
D = Path(__file__).parent
M = json.loads((D / "vo" / "manifest.json").read_text())
FPS = 30
PAD = {  # section: (pad_in, gap, pad_out) seconds — sized to the VIDEO_PROMPT story table (8:00–9:00, demo longest)
    "cold": (1.2, 1.4, 1.8), "title": (5.0, 0.4, 4.5), "intro": (0.9, 0.0, 1.6), "problem": (1.0, 2.6, 2.0), "motivation": (1.2, 0.6, 4.5),
    "turn": (1.0, 0.6, 3.6), "data": (1.0, 2.5, 3.0), "method": (1.0, 2.2, 2.0), "handoff": (0.8, 0.0, 0.9), "demo": (1.2, 3.6, 2.5),
    "hood": (1.0, 1.6, 3.5), "results": (1.0, 1.8, 2.0), "impact": (1.0, 1.4, 2.0), "outro": (1.2, 1.6, 5.0),
}
ORDER = list(PAD)
# presenter takes (make_presenter.py): replace narrator lines in place, or add lines in their own sections
P = json.loads((D / "vo" / "presenter.json").read_text()) if (D / "vo" / "presenter.json").exists() else []
REPL = {p["replaces"]: p for p in P if p["replaces"]}
lines_all = [dict(REPL.get(l["id"], l), section=l["section"], id=l["id"]) for l in M["lines"]]
lines_all += [p for p in P if not p["replaces"]]
NO_GAP = {"s11_b"}  # one continuous take split in two lines: no pause between them
scenes, t = [], 0
for sec in ORDER:
    lines = [l for l in lines_all if l["section"] == sec]
    pin, gap, pout = PAD[sec]
    cur = pin
    ls = []
    for i, l in enumerate(lines):
        e = {"id": l["id"], "text": l["text"], "file": Path(l["file"]).name,
             "from": round(cur * FPS), "dur": math.ceil(l["duration"] * FPS)}
        if "video" in l:
            e["words"], e["video"] = l["words"], l["video"]
        ls.append(e)
        cur += l["duration"] + (gap if i < len(lines) - 1 and l["id"] not in NO_GAP else 0)
    dur = round((cur + pout) * FPS)
    scenes.append({"id": sec, "start": t, "duration": dur, "lines": ls})
    t += dur
out = ("// GENERATED by video/make_timing.py from vo/manifest.json — do not edit by hand.\n"
       "export const FPS = 30;\n"
       "export type Word = {w: string; s: number; e: number};\n"
       "export type Line = {id: string; text: string; file: string; from: number; dur: number; words?: Word[]; video?: {src: string; from_s: number; cx: number; clip: string}};\n"
       "export type SceneTiming = {id: string; start: number; duration: number; lines: Line[]};\n"
       f"export const SCENES: SceneTiming[] = {json.dumps(scenes, indent=1, ensure_ascii=False)};\n"
       f"export const TOTAL = {t};\n"
       "export const scene = (id: string): SceneTiming => SCENES.find((s) => s.id === id)!;\n"
       "export const line = (sceneId: string, lineId: string): Line => scene(sceneId).lines.find((l) => l.id === lineId)!;\n")
(D / "film" / "src" / "timing.ts").write_text(out)
for s in scenes:
    print(f"{s['id']:<11} start {s['start']/FPS:6.1f}s  dur {s['duration']/FPS:5.1f}s  lines {len(s['lines'])}")
print("TOTAL", round(t / FPS, 1), "s =", f"{int(t/FPS)//60}:{int(t/FPS)%60:02d}")
